fn encoded(bits: &str) -> Vec<u8> {
    let mut bytes = vec![0; bits.len().div_ceil(8)];
    for (i, bit) in bits.bytes().enumerate() {
        bytes[i / 8] |= (bit - b'0') << (7 - i % 8);
    }
    bytes
}

#[test]
fn long_huffman_prefixes_decode_exact_values_and_consume_codes() {
    for case in VALUES {
        let table = HuffmanTable::read_custom(&mut Reader::new(case.table)).expect(case.name);
        let data = encoded(&[case.code, case.code, "10100101"].concat());
        let mut reader = Reader::new(&data);
        assert_eq!(table.decode(&mut reader), Ok(case.value), "{}", case.name);
        assert_eq!(table.decode(&mut reader), Ok(case.value), "{}", case.name);
        assert_eq!(reader.read_bits(8), Some(0xa5), "{}", case.name);
        assert_eq!(
            table.has_out_of_band(),
            case.value.is_none(),
            "{}",
            case.name
        );
    }
}

#[test]
fn long_huffman_prefixes_assign_every_complete_tree_value() {
    for width in [1, 2, 31, 32, 33, 64, 127, 128, 254, 255] {
        let lines: Vec<_> = (0..=width)
            .map(|value| TableLine::new(value, (value + 1).min(width) as u8, 0))
            .collect();
        let table = HuffmanTable::build(&lines).unwrap();
        for value in 0..=width {
            let mut code = "1".repeat(value as usize);
            if value < width {
                code.push('0');
            }
            assert_eq!(
                table.decode(&mut Reader::new(&encoded(&code))),
                Ok(Some(value))
            );
        }
        // A complete binary tree has one fewer branch than leaves, regardless
        // of its depth. Deep prefixes must not expand a dense lookup space.
        let InnerHuffmanTable::Dynamic { nodes } = table.0.as_ref() else {
            panic!("dynamic table");
        };
        assert_eq!(nodes.len(), 2 * width as usize + 1);
    }
}

#[test]
fn long_huffman_prefixes_reject_overfilled_trees_and_unassigned_codes() {
    for (data, code, overfilled) in INVALID {
        let table = HuffmanTable::read_custom(&mut Reader::new(data));
        if *overfilled {
            assert_eq!(table.unwrap_err(), HuffmanError::ConflictingCodes.into());
        } else {
            let table = table.unwrap();
            assert!(table.decode(&mut Reader::new(&encoded(code))).is_err());
        }
    }
}

#[test]
fn long_huffman_prefixes_require_complete_table_fields_and_codes() {
    for case in VALUES {
        for end in 0..case.table.len() {
            assert!(HuffmanTable::read_custom(&mut Reader::new(&case.table[..end])).is_err());
        }
        let table = HuffmanTable::read_custom(&mut Reader::new(case.table)).unwrap();
        let data = encoded(case.code);
        // Remove whole bytes so padding cannot restore an omitted code bit.
        for end in 0..data.len() {
            assert!(table.decode(&mut Reader::new(&data[..end])).is_err());
        }
    }
}

#[test]
fn long_huffman_prefixes_uniform_tables_preserve_width_without_narrowing() {
    for width in [1, 32, 33, 255] {
        let table = HuffmanTable::build_uniform(2, width).unwrap();
        for value in 0..2 {
            let code = alloc::format!("{value:0width$b}", width = width as usize);
            assert_eq!(
                table.decode(&mut Reader::new(&encoded(&code))),
                Ok(Some(value))
            );
        }
        let InnerHuffmanTable::Dynamic { nodes } = table.0.as_ref() else {
            panic!("dynamic table");
        };
        assert_eq!(nodes.len(), width as usize + 2);
    }
    for width in [256, u32::MAX] {
        assert_eq!(
            HuffmanTable::build_uniform(2, width).unwrap_err(),
            HuffmanError::PrefixLengthTooLarge.into()
        );
    }
    assert_eq!(
        HuffmanTable::build_uniform(3, 1).unwrap_err(),
        HuffmanError::ConflictingCodes.into()
    );
}
